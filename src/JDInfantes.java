    private void BRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BRegistrarActionPerformed
        SimpleDateFormat s = new SimpleDateFormat("yyyy-MM-dd");
        Infante kid = new Infante(
                TFCurp.getText(),
                TFNombre.getText(),
                CBGenero.getSelectedItem().toString(),
                s.format((Date)SFechaNac.getValue()),
                CBEstado.getSelectedItem().toString()
        );

        if (kid.insertar(cnx.con) == 1) {
            JOptionPane.showMessageDialog(this, "INFANTE REGISTRADO!!");
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "ERROR de Capa 7, Registro no Exitoso!");
        }

    }//GEN-LAST:event_BRegistrarActionPerformed

