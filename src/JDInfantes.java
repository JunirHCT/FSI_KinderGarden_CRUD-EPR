    public void obtenerInfante(Infante kid){
        
        try {
            SimpleDateFormat format = new SimpleDateFormat("yyyy-MM-dd");
            
            TFCurp.setText(kid.curp);
            TFNombre.setText(kid.nombre);
            CBGenero.setSelectedItem(kid.sexo);
            SFechaNac.setValue(format.parse(kid.fecha));
            CBEstado.setSelectedItem(kid.estado);
        } catch (ParseException ex) {
            System.getLogger(JDInfantes.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }
    
    public void desabilitarBoton(boolean estado, int opc){
        if (opc == 0) {
            BActualizar.setEnabled(estado);
            BBorrar.setEnabled(estado);
        } else {
            BRegistrar.setEnabled(estado);
            TFCurp.setEnabled(estado);
        }
        
    }
    
