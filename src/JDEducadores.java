    public void obtenerEducador(Educadores edu) {
        TFCurp.setText(edu.curp);
        TFNombre.setText(edu.nombre);
        CBSexo.setSelectedItem(edu.sexo);
        TFTelefono.setText(edu.telefono);
        TADireccion.setText(edu.direccion);
        CBEstado.setSelectedItem(edu.estado);

    }
    
    public void desabilitarBoton(boolean estado, int opc){
        if (opc == 0) {
            BActualizar.setEnabled(estado);
            BBorrar.setEnabled(estado);
        } else {
            BRegistrar.setEnabled(estado);
            TFCurp.setEnabled(estado);
        }
        
    }

